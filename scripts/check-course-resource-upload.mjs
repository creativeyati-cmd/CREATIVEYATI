import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
registerHooks({resolve(specifier,context,next){
 if(specifier==='@/lib/supabase/server')return {url:'data:text/javascript,'+encodeURIComponent('export const getAdminUser=async()=>globalThis.actor;export const createSupabaseServiceClient=()=>globalThis.db;'),shortCircuit:true};
 if(specifier.startsWith('@/'))return next(pathToFileURL(path.resolve(specifier.slice(2)+'.js')).href,context);
 if(specifier.startsWith('.')&&!path.extname(specifier))return next(specifier+'.js',context);
 return next(specifier,context);
}});
const {POST}=await import('../app/api/admin/course-draft-resource/route.js');
const courseId='11111111-1111-4111-8111-111111111111';
const id='22222222-2222-4222-8222-222222222222';
const storageKey=`${courseId}/draft/${id}.pdf`;
let validPDF=true,exists=true,size=8*1024*1024;
globalThis.actor=null;
globalThis.db={from(){const q={select(){return q},eq(){return q},is(){return q},async maybeSingle(){return {data:exists?{id:courseId}:null}}};return q},storage:{from(){return {async createSignedUploadUrl(key){return {data:{signedUrl:'https://storage.example.test/'+key}}},async list(){return {data:[{name:id+'.pdf',metadata:{size,mimetype:'application/pdf'}}]}},async download(){return {data:new Blob([validPDF?'%PDF-test':'invalid'])}}}}}};
const send=(body)=>POST(new Request('https://example.test/api/admin/course-draft-resource',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({courseId,fileSize:size,mimeType:'application/pdf',fileName:'Workbook.pdf',...body})}));
assert.equal((await send({action:'sign'})).status,401);
globalThis.actor={id:'admin'};
let response=await send({action:'sign'});assert.equal(response.status,200);assert.match((await response.json()).storageKey,/\/draft\/.*\.pdf$/);
response=await send({action:'finalize',storageKey});assert.equal(response.status,200);assert.equal((await response.json()).id,id);
const retry=await send({action:'finalize',storageKey});assert.equal((await retry.json()).id,id);
assert.equal((await send({action:'finalize',storageKey:'other/draft/'+id+'.pdf'})).status,400);
assert.equal((await send({action:'sign',fileSize:26*1024*1024})).status,400);
validPDF=false;assert.equal((await send({action:'finalize',storageKey})).status,422);
validPDF=true;assert.equal((await send({action:'finalize',storageKey,fileSize:size-1})).status,422);
exists=false;assert.equal((await send({action:'sign'})).status,400);
console.log('PASS: PDF upload auth, 8MB direct signing, idempotent finalize, ownership, size limits, magic bytes and saved-course checks');
